-- order_id has no foreign key to beer_order: modules reference each other's data by id only.
CREATE TABLE allocation
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE
);

CREATE TABLE allocation_line
(
    allocation_id BIGINT      NOT NULL REFERENCES allocation (id) ON DELETE CASCADE,
    line_no       INT         NOT NULL,
    upc           VARCHAR(20) NOT NULL,
    quantity      INT         NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (allocation_id, line_no)
);
